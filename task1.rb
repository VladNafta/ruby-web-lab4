# Завдання 1. Перші кроки з рядками в Ruby

# 1. Вивід рядка
puts "Привіт, ясен світ!"

# 2. Додаю до виводу власне ім'я та прізвище
puts "Привіт, ясен світ! Мене звати Владислав Мельник."

# 3. Ім'я та прізвище у змінних, об'єднання рядків через +
first_name = "Владислав"
last_name = "Мельник"
puts "Привіт, ясен світ! Мене звати " + first_name + " " + last_name + "."

# 4. Ім'я та прізвище вводяться з клавіатури
print "Введіть ім'я: "
first_name = gets.chomp
print "Введіть прізвище: "
last_name = gets.chomp
puts "Привіт, ясен світ! Мене звати " + first_name + " " + last_name + "."

# 5. Підстановка змінних у літерал через #{}
puts "Привіт, ясен світ! Мене звати #{first_name} #{last_name}."

# 6. Ім'я та прізвище з першої великої літери
puts "Привіт, ясен світ! Мене звати #{first_name.capitalize} #{last_name.capitalize}."

# 7. Рядковий літерал великими літерами
puts "Привіт, ясен світ!".upcase
